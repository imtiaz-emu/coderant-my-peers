import { mkdir, readdir, readFile, unlink, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const marker = '<!-- Generated by scripts/generate-directory.mjs. Do not edit. -->';
const companyId = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const username = /^[a-z0-9](?:[a-z0-9-]{0,37}[a-z0-9])?$/;
const compare = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

function assert(condition, message) {
  if (!condition) throw new Error(message);
}

function object(value, context) {
  assert(value !== null && typeof value === 'object' && !Array.isArray(value),
    `${context}: expected an object`);
}

function fields(value, allowed, context) {
  for (const key of Object.keys(value)) {
    assert(allowed.includes(key), `${context}: unknown field "${key}"`);
  }
}

function text(value, context) {
  assert(typeof value === 'string' && value.trim().length > 0 &&
    value === value.trim() && !/[\u0000-\u001f\u007f]/.test(value),
  `${context}: expected non-empty, single-line text without surrounding whitespace`);
}

function markdown(value) {
  return value.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/[\\`*_[\]{}()#!|~]/g, '\\$&');
}

function validateMember(member, filename, companies, today) {
  const context = `members/${filename}`;
  object(member, context);
  fields(member, ['github', 'name', 'location', 'contact', 'phoneNumber', 'lastVerified', 'employment'], context);
  assert(typeof member.github === 'string' && username.test(member.github) &&
    !member.github.includes('--'), `${context}: github must be a lowercase GitHub username`);
  assert(filename === `${member.github}.json`, `${context}: filename must match github`);
  text(member.name, `${context}: name`);
  if (member.location !== undefined) text(member.location, `${context}: location`);
  if (member.phoneNumber !== undefined) text(member.phoneNumber, `${context}: phoneNumber`);
  text(member.contact, `${context}: contact`);
  let contact;
  try {
    contact = new URL(member.contact);
  } catch {
    throw new Error(`${context}: contact must be an absolute HTTPS URL`);
  }
  assert(contact.protocol === 'https:' && !contact.username && !contact.password,
    `${context}: contact must be an HTTPS URL without credentials`);
  assert(typeof member.lastVerified === 'string' &&
    /^\d{4}-\d{2}-\d{2}$/.test(member.lastVerified), `${context}: lastVerified must be YYYY-MM-DD`);
  const date = new Date(`${member.lastVerified}T00:00:00Z`);
  assert(!Number.isNaN(date.valueOf()) && date.toISOString().slice(0, 10) === member.lastVerified &&
    member.lastVerified <= today, `${context}: lastVerified must be a real date, not in the future`);
  assert(Array.isArray(member.employment), `${context}: employment must be an array`);
  const seen = new Set();
  for (const [index, job] of member.employment.entries()) {
    const jobContext = `${context}: employment[${index}]`;
    object(job, jobContext);
    fields(job, ['company', 'role', 'status', 'openToReferralRequests'], jobContext);
    assert(typeof job.company === 'string' && Object.hasOwn(companies, job.company),
      `${jobContext}: unknown company "${job.company}"; add it to companies.json`);
    text(job.role, `${jobContext}: role`);
    assert(job.status === 'current' || job.status === 'former',
      `${jobContext}: status must be current or former`);
    assert(typeof job.openToReferralRequests === 'boolean',
      `${jobContext}: openToReferralRequests must be a boolean`);
    const key = `${job.company}:${job.status}`;
    assert(!seen.has(key), `${jobContext}: duplicate company/status; combine roles into one entry`);
    seen.add(key);
  }
}

async function json(filename) {
  try {
    return JSON.parse(await readFile(filename, 'utf8'));
  } catch (error) {
    throw new Error(`Cannot read JSON from ${filename}: ${error.message}`, { cause: error });
  }
}

export async function loadDirectory(root, today = new Date().toISOString().slice(0, 10)) {
  const companies = await json(path.join(root, 'companies.json'));
  object(companies, 'companies.json');
  const names = new Set();
  for (const [id, company] of Object.entries(companies)) {
    assert(companyId.test(id), `companies.json: invalid company ID "${id}"`);
    object(company, `companies.json: ${id}`);
    fields(company, ['name'], `companies.json: ${id}`);
    text(company.name, `companies.json: ${id}: name`);
    const name = company.name.toLowerCase();
    assert(!names.has(name), `companies.json: duplicate company name "${company.name}"`);
    names.add(name);
  }
  const members = [];
  const entries = await readdir(path.join(root, 'members'), { withFileTypes: true });
  for (const entry of entries.sort((a, b) => compare(a.name, b.name))) {
    if (entry.name === '.gitkeep') continue;
    assert(entry.isFile() && entry.name.endsWith('.json'),
      `members/${entry.name}: only JSON profile files are allowed`);
    const member = await json(path.join(root, 'members', entry.name));
    validateMember(member, entry.name, companies, today);
    members.push(member);
  }
  return { companies, members };
}

export function renderDirectory({ companies, members }) {
  const output = new Map();
  const grouped = new Map();
  const profileLink = (member) =>
    `[${markdown(member.name)}](../members/${member.github}.json)`;
  for (const member of members) {
    for (const job of member.employment) {
      if (!grouped.has(job.company)) grouped.set(job.company, []);
      grouped.get(job.company).push({ member, job });
    }
  }
  const ids = [...grouped.keys()].sort((a, b) =>
    compare(companies[a].name.toLowerCase(), companies[b].name.toLowerCase()) || compare(a, b));
  const index = [marker, '', '# Companies', '',
    'Find a company below, then open its current and former employee lists.', '',
    '| Company | Current members | Former members |',
    '| --- | --- | --- | --- |'];
  for (const id of ids) {
    const records = grouped.get(id);
    const count = (status) => records.filter(({ job }) => job.status === status).length;
    index.push(`| [${markdown(companies[id].name)}](./${id}.md) | ${count('current')} | ${count('former')} |`);
    const page = [marker, '', `# ${markdown(companies[id].name)}`, '',
      '[All companies](./README.md) | [All people](../directory/people.md)', '',
      'Employment is self-reported. Check the verification date and contact preferences before reaching out.',
      'Former employment does not imply an ability to refer. Referral availability is not a guarantee.', ''];
    for (const status of ['current', 'former']) {
      page.push(`## ${status === 'current' ? 'Current' : 'Former'} employees`, '');
      const rows = records.filter(({ job }) => job.status === status);
      if (rows.length === 0) {
        page.push('No members listed.', '');
        continue;
      }
      page.push('| Member | GitHub | Role | Open to referral requests | Last verified |',
        '| --- | --- | --- | --- | --- |');
      for (const { member, job } of rows) {
        page.push(`| ${profileLink(member)} | [@${member.github}](https://github.com/${member.github}) | ${markdown(job.role)} | ${job.openToReferralRequests ? 'Yes' : 'No'} | ${member.lastVerified} |`);
      }
      page.push('');
    }
    output.set(`companies/${id}.md`, `${page.join('\n')}\n`);
  }
  if (ids.length === 0) index.push('', 'No member profiles yet. Be the first to contribute!');
  output.set('companies/README.md', `${index.join('\n')}\n`);
  const people = [marker, '', '# People', '',
    '[Browse by company](../companies/README.md)', '',
    'Names need not be unique; GitHub usernames identify members. Contact details are in each profile.', '',
    '| Member | GitHub | Current companies | Location | Last verified |',
    '| --- | --- | --- | --- | --- |'];
  const sorted = [...members].sort((a, b) =>
    compare(a.name.toLowerCase(), b.name.toLowerCase()) || compare(a.github, b.github));
  for (const member of sorted) {
    const current = member.employment.filter((job) => job.status === 'current')
      .map((job) => `[${markdown(companies[job.company].name)}](../companies/${job.company}.md)`).join(', ');
    people.push(`| ${profileLink(member)} | [@${member.github}](https://github.com/${member.github}) | ${current || '-'} | ${member.location ? markdown(member.location) : '-'} | ${member.lastVerified} |`);
  }
  if (members.length === 0) people.push('', 'No member profiles yet.');
  output.set('directory/people.md', `${people.join('\n')}\n`);
  return output;
}

async function existingText(filename) {
  try {
    return await readFile(filename, 'utf8');
  } catch (error) {
    if (error.code === 'ENOENT') return null;
    throw error;
  }
}

export async function generateDirectory(root, { check = false, validate = false, today } = {}) {
  const data = await loadDirectory(root, today);
  if (validate) return [];
  const output = renderDirectory(data);
  const existing = new Set(output.keys());
  try {
    for (const entry of await readdir(path.join(root, 'companies'), { withFileTypes: true })) {
      if (entry.name.endsWith('.md')) {
        assert(entry.isFile(), `companies/${entry.name}: expected a generated regular file`);
        existing.add(`companies/${entry.name}`);
      }
    }
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
  const changes = [];
  for (const filename of [...existing].sort(compare)) {
    const previous = await existingText(path.join(root, filename));
    assert(previous === null || previous.startsWith(`${marker}\n`),
      `${filename}: refusing to overwrite or remove a file without the generated marker`);
    if (previous !== (output.get(filename) ?? null)) changes.push(filename);
  }
  if (check) {
    assert(changes.length === 0,
      `Generated directory is out of date. Run npm run generate. Changed: ${changes.join(', ')}`);
    return changes;
  }
  // Plan and validate every change before modifying any generated files.
  for (const filename of changes) {
    const target = path.join(root, filename);
    if (output.has(filename)) {
      await mkdir(path.dirname(target), { recursive: true });
      await writeFile(target, output.get(filename));
    } else {
      await unlink(target);
    }
  }
  return changes;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  try {
    assert(args.length <= 1 && args.every((arg) => ['--check', '--validate'].includes(arg)),
      'Usage: node scripts/generate-directory.mjs [--check|--validate]');
    const root = fileURLToPath(new URL('../', import.meta.url));
    const changes = await generateDirectory(root, {
      check: args.includes('--check'),
      validate: args.includes('--validate')
    });
    console.log(args.includes('--validate') ? 'Profiles and company registry are valid.' :
      args.includes('--check') ? 'Generated directory is up to date.' :
        `Directory generated: ${changes.length} file(s) changed.`);
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
